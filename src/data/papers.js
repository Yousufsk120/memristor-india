export function filterPapers({ mechanism, material, application, yearRange, search }) {
  return papers.filter(p => {
    if (mechanism && mechanism !== 'All' && !p.mechanism.includes(mechanism)) return false
    if (material && material !== 'All' && !p.material.includes(material.replace('₂', '2').replace('₃', '3'))) return false
    if (application && application !== 'All' && !p.application.includes(application)) return false
    if (yearRange && yearRange !== 'All') {
      const [start, end] = yearRange.split('–').map(Number)
      if (p.year < start || p.year > end) return false
    }
    if (search) {
      const q = search.toLowerCase()
      if (!p.title.toLowerCase().includes(q) &&
          !p.authors.toLowerCase().includes(q) &&
          !p.abstract.toLowerCase().includes(q) &&
          !p.tags.some(t => t.includes(q))) return false
    }
    return true
  })
}
